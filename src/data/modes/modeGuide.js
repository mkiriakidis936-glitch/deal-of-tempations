const FORMAT_ACTS = Object.fromEntries(Object.entries(MOVIE_FORMATS).map(([k, f]) => [k, f.acts]));
export const ENGINE_GUIDE_MODES = ['classic', 'arrest_heist'];
const LOCKDOWN_STAGE = { init: 'level1', l1: 'level1', l2: 'level2', l3: 'level3', exit: 'level4', won: 'level5', lost: 'level4' };

// Η τρέχουσα φάση του παιχνιδιού ως id του οδηγού (ίδιο με τα id των ενοτήτων φωτογραφιών).
export function phaseIdFor(state) {
  const mg = state?.mg || {};
  if (state?.mode === 'lockdown') return LOCKDOWN_STAGE[mg.ld?.stage || 'init'] || 'level1';
  if (state?.mode === 'deal_movie') {
    const cg = mg.cg;
    if (!cg) return 'classic';
    if (cg.status === 'finale') return 'finale';
    return cg.jump || (cg.format && FORMAT_ACTS[cg.format]?.[cg.act || 0]?.continent) || 'classic';
  }
  if (state?.mode === 'villa_takeover') {
    if (!mg.villa) return 'arrival';
    return villaPhaseOf(Number(mg.villa.sq || 1), mg.villa).media;
  }
  if (state?.mode === 'marathon_4h') return `phase${Math.min(4, (mg.lounge?.phase || 0) + 1)}`;
  // Μηχανές: η φάση είναι το πραγματικό στάδιο του παιχνιδιού (state.stage 0–3).
  const engine = ENGINE_GUIDE_MODES.includes(state?.mode) ? MODE_GUIDE[state.mode].phases : null;
  if (engine) return (engine.find((phase) => phase.stage === Number(state.stage || 0)) || engine[0]).id;
  return '';
}

export function currentPhase(state) {
  const guide = MODE_GUIDE[state?.mode];
  if (!guide) return null;
  const id = phaseIdFor(state);
  const index = guide.phases.findIndex((phase) => phase.id === id);
  return index < 0 ? null : { ...guide.phases[index], index, total: guide.phases.length };
}
